CREATE TABLE auditoria_ticket (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT       NOT NULL,
    accion      VARCHAR(20)  NOT NULL,
    detalle     VARCHAR(500) NOT NULL,
    usuario_id  BIGINT       NOT NULL,
    fecha       TIMESTAMP    NOT NULL,
    CONSTRAINT fk_auditoria_ticket FOREIGN KEY (ticket_id) REFERENCES ticket (id),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_auditoria_accion CHECK (accion IN ('CREACION', 'CAMBIO_ESTADO', 'ASIGNACION', 'ELIMINACION'))
);

CREATE INDEX ix_auditoria_ticket ON auditoria_ticket (ticket_id);
CREATE INDEX ix_auditoria_usuario ON auditoria_ticket (usuario_id);
