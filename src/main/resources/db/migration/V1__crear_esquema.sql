CREATE TABLE usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    correo          VARCHAR(150) NOT NULL,
    password        VARCHAR(100) NOT NULL,
    rol             VARCHAR(20)  NOT NULL,
    fecha_creacion  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'SOPORTE', 'USUARIO'))
);

CREATE TABLE ticket (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                  VARCHAR(100)  NOT NULL,
    descripcion             VARCHAR(2000) NOT NULL,
    categoria               VARCHAR(20)   NOT NULL,
    prioridad               VARCHAR(20)   NOT NULL,
    estado                  VARCHAR(20)   NOT NULL,
    usuario_solicitante_id  BIGINT        NOT NULL,
    tecnico_asignado_id     BIGINT,
    resumen_ia              VARCHAR(500)  NOT NULL,
    origen_analisis         VARCHAR(20)   NOT NULL,
    eliminado               BOOLEAN       NOT NULL DEFAULT FALSE,
    fecha_creacion          TIMESTAMP     NOT NULL,
    fecha_actualizacion     TIMESTAMP     NOT NULL,
    fecha_eliminacion       TIMESTAMP,
    CONSTRAINT fk_ticket_solicitante FOREIGN KEY (usuario_solicitante_id) REFERENCES usuario (id),
    CONSTRAINT fk_ticket_tecnico FOREIGN KEY (tecnico_asignado_id) REFERENCES usuario (id),
    CONSTRAINT ck_ticket_titulo CHECK (char_length(titulo) BETWEEN 5 AND 100),
    CONSTRAINT ck_ticket_descripcion CHECK (char_length(descripcion) BETWEEN 20 AND 2000),
    CONSTRAINT ck_ticket_categoria CHECK (categoria IN ('HARDWARE', 'SOFTWARE', 'CONECTIVIDAD', 'ACCESOS', 'OTRO')),
    CONSTRAINT ck_ticket_prioridad CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ck_ticket_estado CHECK (estado IN ('ABIERTO', 'EN_PROCESO', 'RESUELTO', 'CERRADO')),
    CONSTRAINT ck_ticket_origen CHECK (origen_analisis IN ('MODELO_LENGUAJE', 'REGLAS')),
    CONSTRAINT ck_ticket_eliminacion CHECK (eliminado = (fecha_eliminacion IS NOT NULL))
);

CREATE INDEX ix_ticket_estado ON ticket (estado);
CREATE INDEX ix_ticket_categoria ON ticket (categoria);
CREATE INDEX ix_ticket_prioridad ON ticket (prioridad);
CREATE INDEX ix_ticket_solicitante ON ticket (usuario_solicitante_id);
CREATE INDEX ix_ticket_tecnico ON ticket (tecnico_asignado_id);
CREATE INDEX ix_ticket_fecha_creacion ON ticket (fecha_creacion);

CREATE TABLE ticket_etiqueta (
    ticket_id  BIGINT      NOT NULL,
    posicion   INTEGER     NOT NULL,
    etiqueta   VARCHAR(40) NOT NULL,
    CONSTRAINT pk_ticket_etiqueta PRIMARY KEY (ticket_id, posicion),
    CONSTRAINT fk_ticket_etiqueta_ticket FOREIGN KEY (ticket_id) REFERENCES ticket (id) ON DELETE CASCADE,
    CONSTRAINT ck_ticket_etiqueta_posicion CHECK (posicion BETWEEN 0 AND 4)
);

CREATE TABLE historial_estado_ticket (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        BIGINT      NOT NULL,
    estado_anterior  VARCHAR(20),
    estado_nuevo     VARCHAR(20) NOT NULL,
    fecha_cambio     TIMESTAMP   NOT NULL,
    CONSTRAINT fk_historial_ticket FOREIGN KEY (ticket_id) REFERENCES ticket (id) ON DELETE CASCADE,
    CONSTRAINT ck_historial_estado_anterior CHECK (estado_anterior IN ('ABIERTO', 'EN_PROCESO', 'RESUELTO', 'CERRADO')),
    CONSTRAINT ck_historial_estado_nuevo CHECK (estado_nuevo IN ('ABIERTO', 'EN_PROCESO', 'RESUELTO', 'CERRADO'))
);

CREATE INDEX ix_historial_ticket ON historial_estado_ticket (ticket_id);
